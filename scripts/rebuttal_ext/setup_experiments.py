#!/usr/bin/env python
"""Create one isolated working directory per rebuttal experiment.

Each directory under rebuttal_ext_runs/<experiment>/ holds its own run.py shim, copies of the run scripts,
and (once launched) its own checkpoints/ and results/. Only dataset/ is shared, as a symlink, and it is read
only. The directory has no link to _shared_refine_cache, so a run cannot write to the shared banks.

The scripts are generated from the current run scripts with only these changes: the task name suffix, the
bank path, and the overrides listed below. Files outside the working directory are not modified.
"""
from __future__ import annotations

import argparse
import re
import shutil
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_ROOT = REPO_ROOT / "rebuttal_ext_runs"
SCRIPTS = {"gas": "gas_demand", "nsw_load": "nsw_load", "nsw_price": "nsw_price", "traffic": "traffic_count"}
SUBMITTED_TAU = {"gas": 5.0, "nsw_load": 5.0, "nsw_price": 5.0, "traffic": 2.0}

# Direct-news variant: the scalar knobs are held neutral, as in NN1; the submitted objective and rule are kept.
# 1e-12 is numerically zero; config.py turns an explicit 0 back into its default.
NEUTRAL_KNOBS = {
    "DELTA_V3_LAMBDA_NEWS_CAP": "1e-12",
    "DELTA_V3_SHAPE_GAIN_CAP": "1e-12",
    "DELTA_V3_SPIKE_BIAS_CAP": "1e-12",
}
STANDARD = "scripts/run_{script}.sh"
NO_NEWS_1 = "scripts/true_no_news_1/run_{script}.sh"


def experiments() -> dict[str, dict]:
    table = {
        "plain_head": dict(variant="plain_head", template=NO_NEWS_1, bank="blank", overrides={}),
        "direct_news": dict(variant="direct_news", template=STANDARD, bank="real", overrides=NEUTRAL_KNOBS),
        "sens_eventtau": dict(variant="rein", template=STANDARD, bank="eventtau", overrides={}),
        "sens_noconf": dict(variant="rein", template=STANDARD, bank="noconf", overrides={}),
        "sens_latest": dict(variant="rein", template=STANDARD, bank="latest", overrides={}),
    }
    for tau in (1.0, 2.0, 5.0, 10.0):
        name = f"tau{tau:g}"
        table[f"sens_{name}"] = dict(
            variant="rein",
            template=STANDARD,
            bank=name,
            overrides={"DELTA_V3_REGIME_TAU_DAYS": f"{tau:g}"},
            skip={script for script, value in SUBMITTED_TAU.items() if value == tau},
        )
    return table


SHIM = '''#!/usr/bin/env python
"""Generated by scripts/rebuttal_ext/setup_experiments.py. Do not edit."""
import os
import runpy
import sys

REPO_ROOT = {repo!r}
sys.dont_write_bytecode = True
sys.path.insert(0, os.path.join(REPO_ROOT, "scripts", "rebuttal_ext"))
sys.path.insert(0, REPO_ROOT)

from variant_models import install  # noqa: E402

install({variant!r})
runpy.run_path(os.path.join(REPO_ROOT, "run.py"), run_name="__main__")
'''

SOURCE_LINE = re.compile(r'^source "\$(?:SCRIPT_DIR|COMMON_DIR)/_run_forecast_common\.sh"$', re.M)


def render(text: str, *, name: str, dataset: str, spec: dict, banks: Path, smoke: bool) -> str:
    text, n = re.subn(r'^TASK_NAME_BASE="([^"]*)"', lambda m: f'TASK_NAME_BASE="{m.group(1)}_{name}"', text, flags=re.M)
    if n != 1:
        raise ValueError(f"expected one TASK_NAME_BASE, found {n}")
    bank_path = banks / f"{dataset}_{spec['bank']}.npz"
    lines = [f'DELTA_V3_REGIME_BANK_PATH="{bank_path}"']
    lines += [f'{key}="{value}"' for key, value in spec["overrides"].items()]
    if smoke:
        lines += ['HORIZONS=("48")', 'BASE_EPOCHS="1"', 'DELTA_EPOCHS="1"']
    block = "# Rebuttal experiment overrides (generated).\n" + "\n".join(lines) + '\ncd "$REPO_ROOT"\n'
    text, n = SOURCE_LINE.subn(lambda m: block + m.group(0), text)
    if n != 1:
        raise ValueError(f"expected one source line, found {n}")
    return text


def create(name: str, spec: dict, root: Path, banks: Path, smoke: bool) -> None:
    work = root / name
    scripts_dir = work / "scripts"
    scripts_dir.mkdir(parents=True, exist_ok=True)
    shutil.copy2(REPO_ROOT / "scripts" / "_run_forecast_common.sh", scripts_dir / "_run_forecast_common.sh")
    link = work / "dataset"
    if not link.is_symlink():
        link.symlink_to(REPO_ROOT / "dataset")
    (work / "run.py").write_text(SHIM.format(repo=str(REPO_ROOT), variant=spec["variant"]), encoding="utf-8")
    count = 0
    for script, dataset in SCRIPTS.items():
        if script in spec.get("skip", ()):
            continue
        relative = spec["template"].format(script=script)
        target = work / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        rendered = render((REPO_ROOT / relative).read_text(encoding="utf-8"), name=name, dataset=dataset, spec=spec, banks=banks, smoke=smoke)
        target.write_text(rendered, encoding="utf-8")
        target.chmod(0o755)
        count += 1
    print(f"{name}: {count} datasets in {work}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=DEFAULT_ROOT)
    parser.add_argument("--banks", type=Path, default=DEFAULT_ROOT / "banks")
    parser.add_argument("--only", nargs="*", default=None, help="experiment names (default: all)")
    parser.add_argument("--smoke", action="store_true", help="H=48 only, one base epoch and one delta epoch")
    args = parser.parse_args()
    args.root.mkdir(parents=True, exist_ok=True)
    (args.root / ".gitignore").write_text("*\n", encoding="utf-8")
    table = experiments()
    for name in args.only or table:
        create(name, table[name], args.root.resolve(), args.banks.resolve(), args.smoke)


if __name__ == "__main__":
    main()
